"""Writes every Kazakh text into one file for a native speaker to check.

    python tools/kazakh_texts.py           write docs/kazakh-texts-for-review.md
    python tools/kazakh_texts.py --check   fail when the file is out of date
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TEXTS = ROOT / "frontend" / "src" / "i18n"
LANDING = ROOT / "frontend" / "landing" / "src" / "texts.ts"
TARGET = ROOT / "docs" / "kazakh-texts-for-review.md"

_HEAD = """# Қазақша мәтіндер: тексеру парағы / Kazakh texts for review

This file is generated by `python tools/kazakh_texts.py`. Do not edit it by hand: write the
correction in the last column of a copy, then change `frontend/src/i18n/kk.json`,
`frontend/landing/src/texts.ts` and the server files named below, and run the tool again.

Status: **beta**. Written by a language model, not yet read by a native speaker. The quotes from
the law (keys `law.*`) are copied from adilet.zan.kz and must not be changed.

What to check: meaning, spelling, polite form (сіз), terms a bank would use, buttons short enough.
"""


def _load(lang: str) -> dict[str, str]:
    return json.loads((TEXTS / f"{lang}.json").read_text(encoding="utf-8"))


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _interface_rows() -> list[str]:
    kazakh, russian, english = _load("kk"), _load("ru"), _load("en")
    return [
        f"| `{key}` | {_cell(text)} | {_cell(russian[key])} | {_cell(english[key])} | |"
        for key, text in kazakh.items()
    ]


#: One line of the translations object: 'key': 'text' or 'key': "text with an apostrophe".
_LANDING_LINE = re.compile(r"""  '(?P<key>[\w.]+)': (?P<quote>['"])(?P<text>[^\\]*)(?P=quote),""")


def _landing_texts(lang: str) -> dict[str, str]:
    """One language of the translations object of the landing page."""
    source = LANDING.read_text(encoding="utf-8")
    start = re.search(rf"^const {lang}\b.*= {{$", source, re.MULTILINE)
    if not start:
        raise ValueError(f"no texts for {lang} in {LANDING.name}")
    lines = source[start.end() : source.index("\n}", start.end())].strip("\n").split("\n")
    found = [_LANDING_LINE.fullmatch(line) for line in lines]
    if None in found:
        raise ValueError(f"this line of {LANDING.name} cannot be read: {lines[found.index(None)].strip()}")
    return {item["key"]: item["text"] for item in found if item}


def _landing_rows() -> list[str]:
    kazakh, russian, english = _landing_texts("kk"), _landing_texts("ru"), _landing_texts("en")
    return [
        f"| `{key}` | {_cell(text)} | {_cell(russian[key])} | {_cell(english[key])} | |"
        for key, text in kazakh.items()
    ]


def _server_rows() -> list[str]:
    sys.path.insert(0, str(ROOT))
    from bothsides.demo.scenes import SCENES
    from bothsides.demo.seed import background_cases
    from bothsides.clock import SystemClock

    cases, _, _ = background_cases(SystemClock().now(), 1)
    transfers = [scene.transfer for scene in SCENES] + [case.transfer for case in cases]
    people = {person.id: person for item in transfers for person in (item.sender, item.receiver)}
    names = [
        f"| name in `bothsides/demo` | {person.name_kk} | {person.name_ru} | {person.name_en} | |"
        for person in people.values()
    ]
    scripts = [
        f"| scene `{scene.id}`, receiver types | {scene.receiver_script} | | | |"
        for scene in SCENES
        if scene.receiver_script
    ]
    return names + scripts


_KAZAKH_LETTER = re.compile("[әғқңөұүһі]")


def _denials() -> dict[str, Any]:
    return json.loads((ROOT / "bothsides" / "data" / "denials.json").read_text(encoding="utf-8"))


def _word_list_rows() -> list[str]:
    data = _denials()
    return [
        f"| `denials.json` {kind} | {_cell(phrase)} | | | |"
        for kind in ("denial", "coached")
        for phrase in data[kind]["kazakh"]
    ]


def _negation_rows() -> list[str]:
    """Negation words, and the phrases that are no denial although they hold such a word."""
    data = _denials()
    negation = data["negation"]
    words = [("negation", word) for word in (*negation["kazakh"], *negation["kazakh_verb_lookalikes"])]
    phrases = [("exception", phrase) for phrase in (*data["exceptions"], *negation["exceptions"])]
    return [f"| `denials.json` {kind} | {_cell(text)} | | | |" for kind, text in words + phrases if kind == "negation" or _KAZAKH_LETTER.search(text)]


#: One language of a list or of a pair of labels in the interface source.
_MONTHS = re.compile(r"^  (?P<lang>ru|kk|en): \[(?P<items>[^\]]*)\],$", re.MULTILINE)
_LABELS = re.compile(r"^const LANG_(?:LABELS|NAMES)\b.*= \{ ru: '([^']*)', kk: '([^']*)', en: '([^']*)' \}$", re.MULTILINE)


def _source_rows() -> list[str]:
    """Texts that stand in the source of the interface: month names and the language switch."""
    source = ROOT / "frontend" / "src"
    found = _MONTHS.finditer((source / "format.ts").read_text(encoding="utf-8"))
    months = {item["lang"]: re.findall(r"'([^']*)'", item["items"]) for item in found}
    labels = _LABELS.findall((source / "components" / "ui.tsx").read_text(encoding="utf-8"))
    if {len(names) for names in months.values()} != {12} or len(months) != 3 or len(labels) != 2:
        raise ValueError("the month names or the language labels cannot be read")
    month_rows = [
        f"| month {number} in `format.ts` | {kazakh} | {russian} | {english} | |"
        for number, (kazakh, russian, english) in enumerate(zip(months["kk"], months["ru"], months["en"]), start=1)
    ]
    label_rows = [f"| language switch in `ui.tsx` | {kazakh} | {russian} | {english} | |" for russian, kazakh, english in labels]
    return month_rows + label_rows


def _table(title: str, rows: list[str]) -> str:
    head = "| Key | Қазақша | Русский | English | Түзету / Correction |\n|---|---|---|---|---|"
    return f"\n## {title}\n\n{head}\n" + "\n".join(rows) + "\n"


def build() -> str:
    """Return the whole file."""
    return (
        _HEAD
        + _table("Interface", _interface_rows())
        + _table("Dates and the language switch", _source_rows())
        + _table("Landing page", _landing_rows())
        + _table("Names and typed scene texts", _server_rows())
        + _table("Phrases that send a typed answer to a person", _word_list_rows())
        + _table("Negation words of the offline matcher, and phrases that deny nothing", _negation_rows())
    )


def main(arguments: list[str]) -> int:
    text = build()
    if "--check" in arguments:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("docs/kazakh-texts-for-review.md is out of date: run python tools/kazakh_texts.py")
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
